import { isIP } from "node:net"
import { createResult, createResultError, type Result } from "#result"
import { tailscaleHostnameNormalize } from "./tailscaleHostnameNormalize.js"

export type TailscaleDnsmasqConfigRenderInput = {
  nodeAddress: string
  hostnames: readonly string[]
  upstreamResolvers: readonly string[]
  listenLoopback?: boolean
  publicPassthroughs?: readonly string[]
}

/**
 * Render the private dnsmasq split-horizon config: per-host answers for the
 * approved private hostnames only, AAAA returns NODATA (host-record + local),
 * everything else forwards upstream. Only exact-host `host-record=` and
 * `local=/host/` lines are ever emitted; whole-zone overrides are impossible
 * by construction (wildcards and malformed names are rejected).
 *
 * NOTE (DNS-01): private-Caddy `tls { dns ... }` challenge blocks must use
 * explicit public resolvers, never this listener: ACME propagation self-checks
 * answered from split-horizon records diverge from public resolvers.
 */
export function tailscaleDnsmasqConfigRender(input: unknown): Result<string> {
  const op = "tailscaleDnsmasqConfigRender"
  if (typeof input !== "object" || input === null) {
    return createResultError(op, "dnsmasq config input is required")
  }
  const candidate = input as Partial<TailscaleDnsmasqConfigRenderInput>
  if (typeof candidate.nodeAddress !== "string" || isIP(candidate.nodeAddress) !== 4) {
    return createResultError(op, "dnsmasq node address must be an IPv4 address")
  }
  if (!Array.isArray(candidate.hostnames)) {
    return createResultError(op, "dnsmasq hostnames are invalid")
  }
  if (!Array.isArray(candidate.upstreamResolvers) || candidate.upstreamResolvers.length === 0) {
    return createResultError(op, "dnsmasq requires at least one upstream resolver")
  }
  for (const resolver of candidate.upstreamResolvers) {
    if (typeof resolver !== "string" || isIP(resolver) !== 4) {
      return createResultError(op, "dnsmasq upstream resolvers must be IPv4 addresses")
    }
  }
  if (candidate.listenLoopback !== undefined && typeof candidate.listenLoopback !== "boolean") {
    return createResultError(op, "dnsmasq listenLoopback must be a boolean")
  }
  if (candidate.publicPassthroughs !== undefined && !Array.isArray(candidate.publicPassthroughs)) {
    return createResultError(op, "dnsmasq public passthroughs are invalid")
  }
  const hostnames: string[] = []
  const seen = new Set<string>()
  for (const hostname of candidate.hostnames) {
    const normalized = tailscaleHostnameNormalize(hostname)
    if (normalized === undefined) {
      return createResultError(op, `dnsmasq hostname ${JSON.stringify(hostname)} is not an exact FQDN`)
    }
    if (seen.has(normalized)) continue
    seen.add(normalized)
    hostnames.push(normalized)
  }
  hostnames.sort()
  const passthroughs: string[] = []
  const passthroughSeen = new Set<string>()
  for (const passthrough of candidate.publicPassthroughs ?? []) {
    const normalized = tailscaleHostnameNormalize(passthrough)
    if (normalized === undefined) {
      return createResultError(op, `dnsmasq passthrough ${JSON.stringify(passthrough)} is not an exact FQDN`)
    }
    if (seen.has(normalized) || passthroughSeen.has(normalized)) continue
    passthroughSeen.add(normalized)
    passthroughs.push(normalized)
  }
  passthroughs.sort()
  const listenAddresses =
    candidate.listenLoopback === false ? candidate.nodeAddress : `${candidate.nodeAddress},127.0.0.1`
  const lines = [
    "# Generated by project-registry private DNS (split-horizon dnsmasq). Do not hand-edit.",
    "# Private A answers for the approved private hostnames only; AAAA returns NODATA (host-record + local).",
    "# Public passthroughs stay public: most-specific server=/name/upstream forwards",
    "# keep those exact names on upstream resolvers.",
    "# Everything else forwards upstream; never widen hostnames to whole zones.",
    "# NOTE (DNS-01): Caddy tls dns challenges must use explicit public resolvers, never this listener.",
    "port=53",
    "interface=tailscale0",
    "bind-interfaces",
    `listen-address=${listenAddresses}`,
    "no-resolv",
    "bogus-priv",
    "domain-needed",
    ...candidate.upstreamResolvers.map((resolver) => `server=${resolver}`),
    ...passthroughs.flatMap((passthrough) =>
      (candidate.upstreamResolvers as readonly string[]).map((resolver) => `server=/${passthrough}/${resolver}`),
    ),
    ...hostnames.flatMap((hostname) => [`host-record=${hostname},${candidate.nodeAddress}`, `local=/${hostname}/`]),
  ]
  return createResult(`${lines.join("\n")}\n`)
}
